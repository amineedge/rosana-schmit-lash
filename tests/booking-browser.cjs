(async()=>{
 const {createRequire}=await import('node:module');
 const load=createRequire(__filename);
 const {chromium}=load('playwright');
 const {default:assert}=await import('node:assert/strict');
 const browser=await chromium.launch({headless:true});
 for(const width of [393,1440,320]){
 const context=await browser.newContext({viewport:{width,height:width===1440?1000:852}});
 const page=await context.newPage();
 async function inspect(stage){
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width}px: ${stage} overflow`);
  await page.screenshot({path:`/tmp/rosana-${width}-${stage}.png`,fullPage:true});
 }
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',dialog=>dialog.accept());
 await page.goto('http://localhost:4173/agendar.html');
 await page.getByRole('heading',{name:'Um tempo só para o seu olhar.'}).waitFor();
 await page.screenshot({path:'/tmp/rosana-demo-client.png',fullPage:true});
 async function book(name){
  await page.locator('#client-name').fill(name);
  await page.getByRole('button',{name:'Escolher horário →'}).click();
  await inspect('schedule');
  await page.getByRole('button',{name:'09:00',exact:true}).click();
  await page.getByRole('button',{name:'Continuar →',exact:true}).click();
  await inspect('payment');
  await page.getByRole('button',{name:/Simular pagamento de/}).click();
  assert.equal(await page.getByRole('heading',{name:'Seu horário está confirmado.'}).count(),0);
  await page.locator('#accept-policy').check();
  await page.getByRole('button',{name:/Simular pagamento de/}).click();
  await page.getByRole('heading',{name:'Seu horário está confirmado.'}).waitFor();
  await inspect('confirmation');
 }
 await book('Cliente A');
 await page.getByRole('button',{name:'Ver minha reserva',exact:true}).click();
 await page.locator('#scenario').selectOption('late');
 await inspect('cancellation');
 await page.getByRole('button',{name:'Confirmar cancelamento simulado'}).click();
 await page.getByText('Restituição em espera · sinal preservado',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Nova reserva',exact:true}).click();
 await book('Cliente B');
 await page.getByRole('button',{name:'Abrir agenda de Rosana'}).click();
 await page.getByText('Cancelado · Reembolso em processamento',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Simular confirmação do reembolso'}).click();
 await page.getByText('Cancelado · Reembolso confirmado',{exact:false}).waitFor();
 await inspect('dashboard');
 assert.equal(await page.locator('.appointment').count(),2);
 await page.screenshot({path:'/tmp/rosana-demo-dashboard.png',fullPage:true});
 await page.reload();
 await page.getByRole('button',{name:'Agenda de Rosana',exact:true}).click();
 assert.equal(await page.locator('.appointment').count(),2);
 await page.getByRole('button',{name:'Bloquear novos horários'}).click();
 await page.getByText('Dia bloqueado para novas reservas.',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Abrir este dia'}).click();
 await page.locator('.appointment').last().getByRole('button',{name:'Cancelar / opções'}).click();
 await page.locator('#scenario').selectOption('early');
 await page.getByRole('button',{name:'Confirmar cancelamento simulado'}).click();
 await page.getByText(/Cancelado · Crédito disponível/).waitFor();
 await page.getByRole('button',{name:'Criar reserva',exact:true}).click();
 await book('Cliente C');
 await page.getByRole('button',{name:'Ver minha reserva',exact:true}).click();
 await page.locator('#scenario').selectOption('legal');
 await page.getByRole('button',{name:'Confirmar cancelamento simulado'}).click();
 await page.getByText('Reembolso em processamento',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Agenda de Rosana',exact:true}).click();
 await page.locator('#booking-window').selectOption('365');
 await page.getByRole('button',{name:'Criar reserva',exact:true}).click();
 await page.locator('#client-name').fill('Cliente calendário');
 await page.getByRole('button',{name:'Escolher horário →'}).click();
 for(let i=0;i<3;i++)await page.getByRole('button',{name:'Próximo mês',exact:true}).click();
 const distant=await page.locator('.calendar-month button:not([disabled])').first().getAttribute('data-date');
 await page.locator(`[data-date="${distant}"]`).click();
 await page.getByRole('button',{name:'09:00',exact:true}).click();
 await inspect('calendar-distant');
 await page.getByRole('button',{name:'Continuar →',exact:true}).click();
 await page.locator('#accept-policy').check();
 await page.getByRole('button',{name:/Simular pagamento de/}).click();
 await page.getByRole('button',{name:'Abrir agenda de Rosana'}).click();
 assert.equal(await page.locator('#dashboard-day').inputValue(),distant);
 await page.getByRole('button',{name:'Bloquear novos horários'}).click();
 await page.getByRole('button',{name:'Criar reserva',exact:true}).click();
 await page.locator('#client-name').fill('Teste dia bloqueado');
 await page.getByRole('button',{name:'Escolher horário →'}).click();
 assert(await page.locator(`[data-date="${distant}"]`).isDisabled());
 await page.screenshot({path:'/tmp/rosana-demo-mobile.png',fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log(`PASS ${width}px: all screens, deposit acceptance, late/early/legal cancellations, replacement refund, dashboard blocking, persistence, no overflow or runtime errors.`);
 await context.close();
 }
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
